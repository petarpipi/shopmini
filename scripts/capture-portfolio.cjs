const { chromium } = require('@playwright/test');
const fs = require('node:fs/promises');
const path = require('node:path');
const output = path.resolve(__dirname, '../qa/screenshots');
const baseURL = process.env.SHOPMINI_URL || 'http://127.0.0.1:5175';
(async () => {
  await fs.rm(output, { recursive: true, force: true });
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let count = 0;
  const ready = async () => {
    await page.locator('h1').first().waitFor();
    await page.evaluate(async () => {
      for (const image of document.images) image.loading = 'eager';
      await Promise.all(Array.from(document.images).map(image => image.decode().catch(() => undefined)));
      await document.fonts.ready;
    });
    await page.waitForTimeout(700);
  };
  const capture = async (name, fullPage) => {
    await page.screenshot({ path: path.join(output, name + '.png'), fullPage, animations: 'disabled' });
    count += 1;
    console.log(`Saved ${name}.png`);
  };
  const shot = async (name, url, width, height, fullPage = true) => {
    await page.setViewportSize({ width, height });
    await page.goto(baseURL + url);
    await ready();
    await capture(name, fullPage);
  };
  const fillCheckout = async () => {
    await page.getByLabel('First name').fill('Alex');
    await page.getByLabel('Last name').fill('Sample');
    await page.getByRole('textbox', { name: 'Email address', exact: true }).fill('alex@example.com');
    await page.getByRole('button', { name: 'Continue to shipping' }).click();
    await page.getByLabel('Street address').fill('12 Sample Street');
    await page.getByRole('textbox', { name: 'City', exact: true }).fill('Berlin');
    await page.getByLabel('Postal code').fill('10115');
    await page.getByRole('combobox', { name: 'Country', exact: true }).selectOption('Germany');
    await page.getByRole('button', { name: 'Review your order' }).click();
  };
  await shot('01-home-desktop', '/', 1440, 1000, false);
  await shot('02-home-desktop-full', '/', 1440, 1000);
  await shot('03-home-mobile', '/', 390, 844);
  await shot('04-shop-desktop', '/shop', 1440, 1000);
  await shot('05-shop-mobile', '/shop', 390, 844);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(baseURL + '/product/daily-glow-serum');
  await page.getByRole('radio', { name: '50 ml' }).check();
  await page.getByRole('button', { name: 'Add to bag — €56.00' }).click();
  await page.goto(baseURL + '/product/linen-hand-cream');
  await page.getByRole('button', { name: 'Save to your wishlist', exact: true }).click();
  await page.getByRole('button', { name: 'Add to bag — €18.00' }).click();
  await shot('06-product-desktop', '/product/daily-glow-serum', 1440, 1000);
  await shot('07-product-mobile', '/product/velvet-night-cream', 390, 844, false);
  await shot('08-cart-mobile', '/cart', 390, 844);
  await shot('09-cart-desktop', '/cart', 1440, 1000, false);
  await shot('10-checkout-desktop', '/checkout', 1440, 1000, false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(baseURL + '/checkout');
  await ready();
  await page.getByRole('button', { name: 'Continue to shipping' }).click();
  await page.waitForTimeout(500);
  await page.evaluate(() => window.scrollTo(0, document.querySelector('.checkout-step').getBoundingClientRect().top + window.scrollY - 110));
  await page.waitForTimeout(400);
  await capture('11-checkout-validation-mobile', false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(baseURL + '/checkout');
  await ready();
  await fillCheckout();
  await page.waitForTimeout(500);
  await capture('12-checkout-review-desktop', true);
  await page.getByRole('button', { name: 'Complete demo order' }).click();
  await ready();
  await capture('13-demo-confirmation-desktop', false);
  await shot('14-wishlist-mobile', '/wishlist', 390, 844);
  await page.goto(baseURL + '/');
  await ready();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.waitForTimeout(600);
  await capture('15-menu-mobile', false);
  await page.keyboard.press('Escape');
  await shot('16-about-desktop', '/about', 1440, 1000);
  await shot('17-contact-mobile', '/contact', 390, 844);
  await shot('18-home-mobile-viewport', '/', 390, 844, false);
  await fs.writeFile(path.join(output, '../screenshot-results.json'), JSON.stringify({ baseURL, errors, screenshots: count }, null, 2) + '\n');
  await browser.close();
  if (errors.length) process.exitCode = 1;
})().catch(error => { console.error(error); process.exit(1); });
